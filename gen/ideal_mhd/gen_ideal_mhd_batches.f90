program gen_ideal_mhd_batches
    ! Hardware variants of the shared energy definitions; no launch policy.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*), &
                            operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_products, only: jvp, vjp
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_symengine, only: symengine_engine_t, make_symengine_engine
    use fortsym_check, only: suite_t, suite_begin, suite_end, check_identity
    use fortsym_kernel_ir, only: kernel_ir_t, lower_kernel_ir
    use fortsym_kernel_emit, only: kernel_emit_spec_t, emit_fortran_batch_ir, &
                          emit_cuda_batch_ir, TARGET_CUDA, TARGET_FORTRAN_OPENMP_SIMD, &
                                   PRECISION_REAL64, PRECISION_REAL32, PRECISION_MIXED
    use fortsym_string, only: str_t, str, chars
    use ideal_mhd_symbolic, only: coordinate_energy, perpendicular_energy, frozen_energy
    implicit none
    type(arena_t), target :: arena
    type(symengine_engine_t) :: engine
    type(suite_t) :: checks
    type(expr_t) :: x(27), components(3), two, divergence, three, mass
    type(expr_t) :: b(3), d(3, 3), a(3, 3), c(3, 3), identity(3, 3)
    type(expr_t) :: energy, jac, h, xi, expected, zero, one, ab(3), cb(3)
    type(expr_t) :: vars(23), ta, tc, ac, b2, ba, bc
    type(str_t) :: adapters(12), imports(12), exports(12)
    integer :: adapter_count = 0
    character(8) :: name
    character(1024) :: directory, evidence
    character(128) :: revision
    integer :: i, j, k, l, row, col, cpu, cuda
    directory = 'src/generated'; evidence = ''; revision = ''
    if (command_argument_count() >= 1) call get_command_argument(1, directory)
    if (command_argument_count() >= 2) call get_command_argument(2, evidence)
    if (command_argument_count() >= 3) call get_command_argument(3, revision)
    call arena%init()
    engine = make_symengine_engine(arena)
    call suite_begin(checks, 'shared MHD batch identities')
    do i = 1, size(x)
        write (name, '(a,i0)') 'x', i
        x(i) = sym(arena, trim(name))
    end do
    open (newunit=cpu, file=trim(directory)//'/ideal_mhd_batches.f90', status='replace')
   open (newunit=cuda, file=trim(directory)//'/ideal_mhd_batches.cuh', status='replace')
write(cpu, '(a)') '! Generated by gen/ideal_mhd/gen_ideal_mhd_batches.f90; do not edit.'
    write(cuda, '(a)') '// Generated by gen/ideal_mhd/gen_ideal_mhd_batches.f90; do not edit.'
    write (cuda, '(a)') '#pragma once'
    call coordinate_energy(x, components, two, divergence, three)
    call family('mhd_two', two, [x(:14), x(16:21)])
    call family('mhd_three', three, x)
    mass = perpendicular_energy(x(:7))
    call family('mhd_mass', mass, x(:7))

    ! Derive the KS3 bilinear form from the shared frozen-in energy Hessian.
    b = x(:3); vars(:5) = x(:5)
    zero = 0*x(1); one = 1 + zero
    identity = zero
    do j = 1, 3
        identity(j, j) = one
        do i = 1, 3
            k = i + 3*(j - 1)
            write (name, '(a,i0)') 'f', k
            d(i, j) = sym(arena, trim(name))
            a(i, j) = x(5 + k); c(i, j) = x(14 + k)
        end do
    end do
    vars(6:) = x(6:23)
    energy = frozen_energy(d, b, x(4), x(5), one, jac)
    ta = zero; tc = zero; ac = zero; b2 = zero; ba = zero; bc = zero
    ab = zero; cb = zero
    do i = 1, 3
        ta = ta + a(i, i); tc = tc + c(i, i); b2 = b2 + b(i)**2
        do j = 1, 3
            ac = ac + a(i, j)*c(j, i)
            ab(i) = ab(i) + a(i, j)*b(j)
            cb(i) = cb(i) + c(i, j)*b(j)
        end do
        ba = ba + b(i)*ab(i); bc = bc + b(i)*cb(i)
    end do
    expected = -(ba*tc + bc*ta)/x(5) &
               + (b2/(2*x(5)) - x(4))*ta*tc + (b2/(2*x(5)) + x(4))*ac
    do i = 1, 3
        expected = expected + ab(i)*cb(i)/x(5)
    end do
    xi = zero
    do j = 1, 9
        row = 1 + mod(j - 1, 3); col = 1 + (j - 1)/3
        do i = 1, 9
            k = 1 + mod(i - 1, 3); l = 1 + (i - 1)/3
            h = diff(diff(energy, d(k, l)), d(row, col))
            do l = 1, 3
                do k = 1, 3
                    h = subs(h, d(k, l), identity(k, l))
                end do
            end do
            call check_identity(checks, engine, 'xi Hessian coefficient', &
                                h - diff(diff(expected, x(5 + i)), x(14 + j)))
            xi = xi + h*x(5 + i)*x(14 + j)
        end do
    end do
    call check_identity(checks, engine, 'xi Hessian contraction', xi - expected)
    call family('mhd_xi', xi, vars)
    write (cpu, '(a)') 'module ideal_mhd_batch'
    do i = 1, adapter_count
        write (cpu, '(a)') chars(imports(i))
    end do
    write (cpu, '(a)') 'use, intrinsic :: iso_fortran_env, only: real32, real64'
    write (cpu, '(a)') 'implicit none'
    write (cpu, '(a)') 'private'
    do i = 1, adapter_count
        write (cpu, '(a)') chars(exports(i))
    end do
    write (cpu, '(a)') 'contains'
    do i = 1, adapter_count
        write (cpu, '(a)') chars(adapters(i))
    end do
    write (cpu, '(a)') 'end module ideal_mhd_batch'
    close (cpu); close (cuda)
    if (len_trim(evidence) > 0) then
        call suite_end(checks, trim(evidence))
    else
        call suite_end(checks)
    end if
contains
    subroutine family(prefix, value, variables)
        character(*), intent(in) :: prefix
        type(expr_t), intent(in) :: value, variables(:)
        type(expr_t) :: direction(size(variables)), seed(1)
        type(expr_t), allocatable :: tangent(:), reverse(:), roots(:), inputs(:)
        type(engine_result_t) :: simplified
        type(kernel_ir_t) :: ir
        type(kernel_emit_spec_t) :: spec
        type(str_t) :: source
        integer, parameter :: precisions(3) = &
                              [PRECISION_REAL64, PRECISION_REAL32, PRECISION_MIXED]
        character(5), parameter :: suffix(3) = ['fp64 ', 'fp32 ', 'mixed']
        character(:), allocatable :: message, code, kernel, in_kind, out_kind
        character(12) :: ni, no, idx
        integer :: n, at, variant
        logical :: good
        n = size(variables)
        do at = 1, n
            write (name, '(a,i0)') 'v', at
            direction(at) = sym(arena, trim(name))
        end do
        seed(1) = sym(arena, 'seed')
        tangent = jvp([value], variables, direction)
        reverse = vjp([value], variables, seed)
        inputs = [variables, direction, seed]
        roots = [value, tangent, reverse]
        do at = 1, size(roots)
            simplified = engine%simplify(roots(at))
            if (.not. simplified%ok) error stop 'MHD simplification failed'
            call check_identity(checks, engine, prefix//' batch root', &
                                roots(at) - simplified%value)
            roots(at) = simplified%value
        end do
        call lower_kernel_ir(roots, ir, good, message)
        if (.not. good) error stop message
        allocate (spec%args(size(inputs)), spec%outputs(size(roots)))
        do at = 1, size(inputs)
            spec%args(at) = inputs(at)%name()
        end do
        do at = 1, size(roots)
            write (name, '(a,i0)') 'y', at
            spec%outputs(at) = str(trim(name))
        end do
        spec%pure_procedure = .true.
        spec%batch_inline = .true.
        spec%batch_threaded = .true.
        spec%generator = str('gen/ideal_mhd/gen_ideal_mhd_batches.f90')
        spec%generator_revision = str(trim(revision))
        do variant = 1, 3
            kernel = prefix//'_'//trim(suffix(variant))
            spec%name = str(prefix//'_'//trim(suffix(variant)))
            spec%precision = precisions(variant)
            spec%target = TARGET_FORTRAN_OPENMP_SIMD
            source = emit_fortran_batch_ir(ir, spec, good, message)
            if (.not. good) error stop message
            write (cpu, '(a)') chars(source)
            adapter_count = adapter_count + 1
            imports(adapter_count) = str('use '//kernel// &
                                         '_batch_mod, only: '//kernel//'_batch')
            exports(adapter_count) = str('public :: '//kernel)
            in_kind = 'real64'; out_kind = 'real64'
            if (variant > 1) in_kind = 'real32'
            if (variant == 2) out_kind = 'real32'
            write (ni, '(i0)') size(inputs); write (no, '(i0)') size(roots)
            code = 'subroutine '//kernel//'(n, inputs, outputs)'//new_line('a')// &
                   'integer, intent(in) :: n'//new_line('a')// &
                   'real('//in_kind//'), intent(in) :: inputs(n,'//trim(ni)//')'// &
                   new_line('a')//'real('//out_kind//'), intent(out) :: outputs(n,'// &
             trim(no)//')'//new_line('a')//'call '//kernel//'_batch(n, &'//new_line('a')
            do at = 1, size(inputs)
                write (idx, '(i0)') at
                code = code//'inputs(:,'//trim(idx)//'), &'//new_line('a')
            end do
            do at = 1, size(roots)
                write (idx, '(i0)') at
                code = code//'outputs(:,'//trim(idx)//')'
                if (at < size(roots)) code = code//', &'//new_line('a')
            end do
            code = code//')'//new_line('a')//'end subroutine '//kernel//new_line('a')
            adapters(adapter_count) = str(code)
            spec%target = TARGET_CUDA
            source = emit_cuda_batch_ir(ir, spec, good, message)
            if (.not. good) error stop message
            write (cuda, '(a)') chars(source)
        end do
    end subroutine family
end program gen_ideal_mhd_batches
